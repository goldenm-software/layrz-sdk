/// [_registeredAppListDecoder] decodes a raw listing `result` payload into a list of [RegisteredApp].
/// Used by listing queries (fetchAll, fetch, fetchPickAndApp, fillAuthorizations).
List<RegisteredApp> _registeredAppListDecoder(Object? json) {
  return List<RegisteredApp>.from(
    (json as List).map((e) {
      return RegisteredApp.fromJson(e as Map<String, dynamic>);
    }),
  );
}

/// [_registeredAppDecoder] decodes a single-object `result` payload into a [RegisteredApp].
/// Used by result-bearing mutations (register/edit-style).
RegisteredApp _registeredAppDecoder(Object? json) {
  return RegisteredApp.fromJson(json as Map<String, dynamic>);
}

/// An application registered in the Layrz platform.
///
/// [RegisteredApp] represents an app registered by a workspace or a partner,
/// including its identity, technology stack, legal and design information,
/// deployed [instances], imported entities, allowed reports, authorized map
/// layers, and push notification credentials.
@freezed
