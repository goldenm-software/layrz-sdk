  /// Private constructor used by the code generator.
  const RegisteredApp._();

  /// Constructs an immutable [RegisteredApp].
  const factory RegisteredApp({
    /// The unique identifier of the app.
    required String id,

    /// The name of the app. It is a fixed name, not a translation key.
    required String name,

    /// The technology of the app.
    @JsonKey(unknownEnumValue: AppTechnology.flutter) @Default(AppTechnology.flutter) AppTechnology technology,

    /// The legal information of the app.
    AppLegal? legalInformation,

    /// The design information of the app.
    AppDesign? designInformation,

    /// The user-facing nickname of the app.
    required String nickname,

    /// Whether the app has been customized, or null when not applicable.
    bool? isCustomized,

    /// The list of deployed instances of the app, or null when not
    /// requested.
    List<AppInstance>? instances,

    /// The list of assets imported into the app, or null when not
    /// requested.
    List<Asset>? importedAssets,

    /// The list of devices imported into the app, or null when not
    /// requested.
    List<Device>? importedDevices,

    /// The list of users imported into the app, or null when not
    /// requested.
    List<User>? importedUsers,

    /// The list of users granted access to the app, or null when not
    /// requested.
    List<User>? keychain,

    /// The identifier of the source this app was created from.
    required String sourceId,

    /// The owner of the app.
    ///
    /// Important: this field is only available when the query is made from
    /// `/goldenm/graphql`.
    User? owner,

    /// The list of reports allowed to be generated by the app, or null when
    /// not requested.
    List<CustomReport>? allowedReports,

    /// The identifier of the fixed workspace of the app, or null when not
    /// applicable.
    String? fixedWorkspaceId,

    /// The fixed workspace of the app, or null when not applicable.
    Workspace? fixedWorkspace,

    /// The list of map layers authorized to be used by the app.
    @Default([]) List<MapLayer> authorizedLayers,

    /// The decrypted iOS Firebase credentials for `layrz_push`, or null when
    /// not set or not requested.
    PushSecrets? iosPushSecrets,

    /// The decrypted Android Firebase credentials for `layrz_push`, or null
    /// when not set or not requested.
    PushSecrets? androidPushSecrets,

    /// Whether the backend holds service-account push credentials; content
    /// is never exposed. Null when not requested.
    bool? hasSvcPushSecrets,
  }) = _RegisteredApp;

