/// A custom report definition allowed to be generated by one or more apps.
///
/// [CustomReport] pairs a report [code] with the list of [RegisteredApp]s
/// authorized to generate it. It forms a circular reference with
/// [RegisteredApp] (via [RegisteredApp.allowedReports]) and therefore lives
/// in the same library as [RegisteredApp].
@freezed
abstract class CustomReport with _$CustomReport {
  /// Private constructor used by the code generator.
  const CustomReport._();

  /// Constructs an immutable [CustomReport].
  const factory CustomReport({
    /// The unique identifier of the report.
    required String id,

    /// The code of the report.
    required String code,

    /// The list of apps allowed to generate this report, or null when not
    /// requested.
    List<RegisteredApp>? allowedApps,
  }) = _CustomReport;

  /// Deserializes a [CustomReport] from a JSON map.
  factory CustomReport.fromJson(Map<String, dynamic> json) => _$CustomReportFromJson(json);
}
