/// Mutable input used to create or update an [OutboundService].
///
/// The API clears every association list that is sent, so [assetsIds], [groupsIds] and [structure]
/// default to empty and are always sent.
@unfreezed
abstract class OutboundServiceInput with _$OutboundServiceInput {
  const OutboundServiceInput._();

  /// Constructs a mutable [OutboundServiceInput].
  factory OutboundServiceInput({
    /// The ID of the service, `null` when creating a new one.
    String? id,

    /// The name of the service.
    @Default('') String name,

    /// The protocol credentials.
    @Default({}) Map<String, dynamic> credentials,

    /// The ID of the protocol.
    String? protocolId,

    /// The IDs of the directly linked assets.
    @Default([]) List<String> assetsIds,

    /// The IDs of the tags linked as groups.
    @Default([]) List<String> groupsIds,

    /// The payload structure, used by the Omega REST and ATS Stream protocols.
    @Default([]) List<OutboundStructureInput> structure,

    /// The read-only token generated by Layrz, never sent by [save] unless set.
    @JsonKey(includeIfNull: false) String? token,

    /// The ATS Stream model, only used by the ATS Stream protocol.
    @JsonKey(unknownEnumValue: AtsStreamModel.exit) AtsStreamModel? atsModel,
  }) = _OutboundServiceInput;

  /// Deserializes an [OutboundServiceInput] from a JSON map.
  factory OutboundServiceInput.fromJson(Map<String, dynamic> json) => _$OutboundServiceInputFromJson(json);

  /// Builds an [OutboundServiceInput] that edits [service], deep copying its credentials and lists.
  ///
  /// Pass the full record from [OutboundService.fetch].
  factory OutboundServiceInput.fromService(OutboundService service) {
    return OutboundServiceInput(
      id: service.id,
      name: service.name,
      credentials: _deepCopyJsonMap(service.credentials ?? const {}),
      protocolId: service.protocolId,
      assetsIds: [...?service.assetsIds],
      groupsIds: [...?service.groupsIds],
      structure: [for (final entry in service.structure ?? const <OutboundStructure>[]) .fromStructure(entry)],
      atsModel: service.atsModel,
    );
  }

  /// Returns a deep copy of this input.
  OutboundServiceInput copy() => OutboundServiceInput.fromJson(_deepCopyJsonMap(toJson()));

  // coverage:ignore-start
  /// Creates the service when [id] is `null`, otherwise updates it, scoped to [appId] when set.
  ///
  /// Returns the [ApiStatus], the field errors (if any) and the saved [OutboundService].
  Future<StandardResponse<OutboundService>> save({
    /// [apiToken] is the API token for authentication.
    required String apiToken,

    /// [uri] is the Layrz GraphQL API endpoint.
    required Uri uri,

    /// [appId] is the ID of the app the mutation is performed from, if any.
    String? appId,

    /// [onResponse] is invoked with the [ApiStatus] when the request does not succeed.
    ValueChanged<ApiStatus>? onResponse,
  }) async {
    final connector = LayrzConnector(apiToken: apiToken, uri: uri);
    final mutationName = id == null ? 'addOutboundService' : 'editOutboundService';
    try {
      final response = await connector.mutate(
        GqlMutation(
          name: mutationName,
          variables: [
            GqlVariable(
              name: 'data',
              value: toJson(),
              type: .input(of: 'OutboundServiceInput'),
              isRequired: true,
            ),
            GqlVariable(name: 'appId', value: appId, type: .id),
          ],
          fields: [
            GqlField(name: mutationName, args: {'data': 'data', 'appId': 'appId'})
              ..add(GqlField(name: 'status'))
              ..add(GqlField(name: 'errors'))
              ..add(GqlField(name: 'result', fragment: OutboundService.fragment)),
          ],
        ),
        _outboundServiceDecoder,
      );

      if (response.status != .ok) {
        onResponse?.call(response.status);
        return (response.status, response.errors, null);
      }

      return (response.status, null, response.result);
    } catch (err, stack) {
      Log.critical("layrz_sdk/OutboundServiceInput/save(): General exception => $err\n$stack");
      onResponse?.call(.internalError);
      return (ApiStatus.internalError, null, null);
    }
  }
  // coverage:ignore-end
}

/// Mutable input of one [OutboundStructure] entry, sent as `OutboundStructureInput`.
@unfreezed
abstract class OutboundStructureInput with _$OutboundStructureInput {
  const OutboundStructureInput._();

  /// Constructs a mutable [OutboundStructureInput].
  factory OutboundStructureInput({
    /// The name of the destination field.
    @Default('newField') String field,

    /// The wire value of the field type, an [OutboundStructureType] or an [AtsStreamExitStructureType].
    @Default('constant') String type,

    /// The constant value, date format or custom field key, depending on [type].
    @Default('') String value,

    /// The source collection to iterate, only used when [type] is `json.array`.
    String? source,

    /// The nested entries, only used when [type] is `json` or `json.array`.
    @Default([]) List<OutboundStructureInput> nested,
  }) = _OutboundStructureInput;

  /// Deserializes an [OutboundStructureInput] from a JSON map.
  factory OutboundStructureInput.fromJson(Map<String, dynamic> json) => _$OutboundStructureInputFromJson(json);

  /// Builds an [OutboundStructureInput] that edits [structure], copying its nested entries.
  factory OutboundStructureInput.fromStructure(OutboundStructure structure) {
    return OutboundStructureInput(
      field: structure.field,
      type: structure.type,
      value: structure.value,
      source: structure.source,
      nested: [for (final entry in structure.nested) .fromStructure(entry)],
    );
  }
}

Map<String, dynamic> _deepCopyJsonMap(Map<String, dynamic> json) {
  Object? walk(Object? value) {
    if (value is Map) return <String, dynamic>{for (final e in value.entries) e.key.toString(): walk(e.value)};
    if (value is List) return [for (final e in value) walk(e)];
    return value;
  }

  return walk(json) as Map<String, dynamic>;
}
